#!/usr/bin/env python3
"""Generate every Cookbook recipe page from canonical data + a shared template."""
import html
import json
import re
from fractions import Fraction
from pathlib import Path
from urllib.parse import urlsplit
from migrate import process

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "templates" / "recipe.html"
MANIFEST = ROOT / "data" / "generated_paths.json"
GENERATED_MARKER = "<!-- Generated by Cookbook; edit data/recipes.json, not this page. -->\n"

def escape(value):
    return html.escape(str(value), quote=True)

def pretty_quantity(value):
    if value is None:
        return ""
    if value == int(value):
        return str(int(value))
    whole = int(value)
    remainder = float(value - whole)
    fraction = Fraction(remainder).limit_denominator(8)
    if abs(float(fraction) - remainder) <= 0.02:
        symbols = {
            (1, 8): "⅛", (1, 6): "⅙", (1, 4): "¼", (1, 3): "⅓",
            (3, 8): "⅜", (1, 2): "½", (5, 8): "⅝", (2, 3): "⅔",
            (3, 4): "¾", (5, 6): "⅚", (7, 8): "⅞",
        }
        if fraction.numerator == fraction.denominator:
            return str(whole + 1)
        symbol = symbols.get((fraction.numerator, fraction.denominator))
        if symbol:
            return str(whole) + symbol if whole else symbol
    return str(round(value, 2))

def ingredient_label(ingredient):
    qty = ingredient.get("quantity")
    amount = pretty_quantity(qty) + " " if qty is not None else ""
    unit = str(ingredient.get("unit") or "")
    name = str(ingredient["name"])
    note = str(ingredient.get("note") or "")
    result = amount + (unit + " " if unit else "") + name
    if note:
        result += ", " + note
    if ingredient.get("optional"):
        result += " (optional)"
    return result

def safe_link(value):
    if not isinstance(value, str):
        return None
    parsed = urlsplit(value)
    if parsed.scheme in ("https", "http") and parsed.netloc:
        return value
    # Relative static assets, without directory traversal or protocol-relative redirects.
    if not parsed.scheme and not parsed.netloc and not value.startswith(("/", "../")) and ".." not in Path(parsed.path).parts:
        return value
    return None

def duration(value):
    if value is None:
        return "Not listed"
    minutes = int(round(value))
    if minutes >= 60:
        hours, rest = divmod(minutes, 60)
        return str(hours) + " hr" + (" " + str(rest) + " min" if rest else "")
    return str(minutes) + " min"

def render(recipe, template):
    title = recipe["title"]
    image = safe_link(recipe.get("image"))
    source = recipe.get("source") or {}
    src = safe_link(source.get("url")) if isinstance(source, dict) else None
    original = recipe.get("original_servings")
    chosen = original if isinstance(original, int) and 1 <= original <= 10 else 1
    options = "".join('<option value="' + str(n) + '"' +
                      (" selected" if n == chosen else "") + ">" +
                      str(n) + "</option>" for n in range(1, 11))
    serialized = json.dumps(recipe, ensure_ascii=False, separators=(",", ":"))
    serialized = (serialized.replace("&", "\\u0026")
                  .replace("<", "\\u003c").replace(">", "\\u003e"))
    ingredients = "".join("<li>" + escape(ingredient_label(i)) + "</li>" for i in recipe["ingredients"])
    instructions = "".join("<li>" + escape(step) + "</li>" for step in recipe["instructions"])
    replacements = {
        "TITLE": escape(title),
        "DESCRIPTION_ATTR": escape(recipe.get("description") or title),
        "DESCRIPTION": escape(recipe.get("description") or ""),
        "CATEGORY": escape(recipe["category"]),
        "PREP": escape(duration(recipe.get("prep_time_minutes"))),
        "COOK": escape(duration(recipe.get("cook_time_minutes"))),
        "TOTAL": escape(duration(recipe.get("total_time_minutes"))),
        "DIFFICULTY": escape(recipe.get("difficulty") or "Not listed"),
        "COUNT": str(recipe["ingredient_count"]),
        "SELECT_DISABLED": "" if original is not None else "disabled",
        "SERVINGS_OPTIONS": options,
        "SCALING_NOTE": ("Amounts are scaled from " + str(original) + " original servings. Season to taste."
                         if original is not None else "Original yield unavailable; scaling disabled."),
        "INGREDIENTS": ingredients,
        "INSTRUCTIONS": instructions,
        "RECIPE_JSON": serialized,
        "IMAGE_HTML": ('<img class="hero-image" loading="lazy" src="' +
                       escape(image) + '" alt="' + escape(title) + '">' if image else ""),
        "SOURCE_HTML": ('<p class="source">Original recipe: <a href="' +
                        escape(src) + '" rel="noopener noreferrer" target="_blank">' +
                        escape(src) + "</a></p>" if src else ""),
    }
    rendered = template
    for token, value in replacements.items():
        rendered = rendered.replace("{{" + token + "}}", value)
    if re.search(r"\{\{[A-Z_]+\}\}", rendered):
        raise ValueError("Unfilled template token for " + title)
    return GENERATED_MARKER + rendered

def generated_listing(recipes):
    return [{
        "title": recipe["title"],
        "slug": recipe["slug"],
        "category": recipe["category"],
        "description": recipe.get("description", ""),
        "ingredients": [i["name"] for i in recipe["ingredients"]],
        "url": "./" + recipe["category"].lower() + "/" + recipe["slug"] + "/",
        "image": recipe.get("image"),
        "difficulty": recipe.get("difficulty"),
        "ingredient_count": recipe["ingredient_count"],
        "prep_time_minutes": recipe.get("prep_time_minutes"),
        "cook_time_minutes": recipe.get("cook_time_minutes"),
        "total_time_minutes": recipe.get("total_time_minutes"),
    } for recipe in recipes]

def build():
    recipes, warnings = process()
    template = TEMPLATE.read_text(encoding="utf-8")
    previous = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else []
    if not isinstance(previous, list):
        raise ValueError("Generated path manifest must be an array")
    current = []
    for recipe in recipes:
        rel = recipe["category"].lower() + "/" + recipe["slug"] + "/index.html"
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(recipe, template), encoding="utf-8")
        current.append(rel)

    # Only remove obsolete files previously generated by this script.
    for rel in set(previous) - set(current):
        if not isinstance(rel, str) or not re.fullmatch(r"[a-z]+/[a-z0-9-]+/index\.html", rel):
            raise ValueError("Unsafe generated path in manifest")
        path = ROOT / rel
        if path.exists() and path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            path.unlink()
            path.parent.rmdir()

    (ROOT / "recipes.json").write_text(
        json.dumps(generated_listing(recipes), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")
    MANIFEST.write_text(json.dumps(current, indent=2) + "\n", encoding="utf-8")
    print("Built " + str(len(recipes)) + " recipe pages and the homepage listing.")
    for warning in warnings:
        print("REVIEW: " + warning)

if __name__ == "__main__":
    build()
